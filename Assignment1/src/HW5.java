public class HW5 {
    public static void main(String[] args) {
        int W=1,G=2,K=3,A=4;
        System.out.println("Before Swapping");
        System.out.println("W :"+W );
        System.out.println("G :"+G);
        System.out.println("k :"+K);
        System.out.println("A :"+A);
        int N;
        N=W;
        W=G;
        G=K;
        K=A;
        A=N;
        System.out.println("After swapping ");
        System.out.println("W :"+W );
        System.out.println("G :"+G);
        System.out.println("k :"+K);
        System.out.println("A :"+A);




    }
}
